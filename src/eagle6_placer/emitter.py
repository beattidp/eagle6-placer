"""Human-reviewable CadSoft EAGLE v6.6.0 ``.scr`` script and JSON report emitter.

Safety invariant: never mutates ``.brd`` or ``.sch`` XML files directly. All
placement edits are emitted as standalone EAGLE ``.scr`` scripts so they can
be dry-run via ``eagle6-mcp`` (``validate_edit_script`` + ``run_drc``) and
executed inside EAGLE GUI with full Undo support.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from pathlib import Path

from eagle6_placer import __version__
from eagle6_placer.geometry import Point2D
from eagle6_placer.models import BoardModel
from eagle6_placer.optimizer import OptimizationResult


@dataclass(frozen=True)
class ComponentDelta:
    """Placement delta for a single moved or rotated unlocked component."""

    name: str
    package: str
    initial_x_mm: float
    initial_y_mm: float
    initial_rot: str
    new_x_mm: float
    new_y_mm: float
    new_rot: str
    displacement_mm: float
    moved: bool
    rotated: bool


class EagleScriptEmitter:
    """Emits CadSoft EAGLE v6 ``.scr`` placement scripts and JSON reports."""

    def __init__(self, position_eps_mm: float = 1e-4) -> None:
        self.position_eps_mm = position_eps_mm

    def compute_deltas(
        self, board: BoardModel, result: OptimizationResult
    ) -> list[ComponentDelta]:
        """Compute sorted list of changed unlocked components.

        Raises:
            AssertionError: If any locked component's pose changed (safety
                defense-in-depth).
        """
        deltas: list[ComponentDelta] = []

        for name in sorted(board.components.keys()):
            comp = board.components[name]
            init_pose = comp.initial_pose
            new_pose = result.best_state.poses[name]

            if comp.is_locked:
                if new_pose != init_pose:
                    raise AssertionError(
                        f"Safety violation: locked component {name!r} was modified"
                    )
                continue

            disp = Point2D(init_pose.x, init_pose.y).distance_to(
                Point2D(new_pose.x, new_pose.y)
            )
            moved = disp > self.position_eps_mm
            init_rot = init_pose.to_eagle_rot()
            new_rot = new_pose.to_eagle_rot()
            rotated = init_rot != new_rot

            if moved or rotated:
                deltas.append(
                    ComponentDelta(
                        name=name,
                        package=comp.footprint.name,
                        initial_x_mm=round(init_pose.x, 4),
                        initial_y_mm=round(init_pose.y, 4),
                        initial_rot=init_rot,
                        new_x_mm=round(new_pose.x, 4),
                        new_y_mm=round(new_pose.y, 4),
                        new_rot=new_rot,
                        displacement_mm=round(disp, 4),
                        moved=moved,
                        rotated=rotated,
                    )
                )
        return deltas

    def render_script(
        self, board: BoardModel, result: OptimizationResult
    ) -> str:
        """Render a commented CadSoft EAGLE v6.6.0 ``.scr`` placement script."""
        deltas = self.compute_deltas(board, result)
        init_c = result.initial_cost
        best_c = result.best_cost
        now_utc = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

        lines = [
            f"# Generated by eagle6-placer v{__version__} at {now_utc}",
            f"# Source board: {board.source_path}",
            f"# Seed: {result.seed} | Steps: {result.steps_executed} | Moved/Rotated: {len(deltas)}",
            (
                f"# Weighted MST wirelength: {init_c.weighted_mst_wirelength_mm:.2f} mm -> "
                f"{best_c.weighted_mst_wirelength_mm:.2f} mm"
            ),
            (
                f"# Raw MST wirelength:      {init_c.raw_mst_wirelength_mm:.2f} mm -> "
                f"{best_c.raw_mst_wirelength_mm:.2f} mm"
            ),
            (
                f"# Airwire crossings:       {init_c.airwire_crossings} -> "
                f"{best_c.airwire_crossings}"
            ),
            (
                f"# Total cost:              {init_c.total_cost:.2f} -> "
                f"{best_c.total_cost:.2f}"
            ),
            "# Safety: Locked components are untouched; review & dry-run via eagle6-mcp before GUI execution.",
            "",
            "GRID MM;",
        ]

        for d in deltas:
            lines.append(
                f"# {d.name} ({d.package}): ({d.initial_x_mm:.4f}, {d.initial_y_mm:.4f}) {d.initial_rot} -> "
                f"({d.new_x_mm:.4f}, {d.new_y_mm:.4f}) {d.new_rot} [disp={d.displacement_mm:.2f}mm]"
            )
            # Engineering rationale: Always single-quote component names in
            # EAGLE v6 .scr commands (e.g. ROTATE =R0 'R1';). Without quotes,
            # CadSoft EAGLE v6's ROTATE parser misinterprets unquoted resistor
            # designators like R1/R2 as rotation-angle tokens (1 deg, 2 deg)
            # and silently skips rotating the component.
            if d.rotated:
                lines.append(f"ROTATE ={d.new_rot} '{d.name}';")
            if d.moved:
                lines.append(f"MOVE '{d.name}' ({d.new_x_mm:.4f} {d.new_y_mm:.4f});")

        lines.extend(["RATSNEST;", "GRID LAST;", ""])
        return "\n".join(lines)

    def build_report(
        self,
        board: BoardModel,
        result: OptimizationResult,
        script_path: Path | None = None,
    ) -> dict[str, object]:
        """Build a JSON-serializable metrics and audit report."""
        deltas = self.compute_deltas(board, result)
        return {
            "tool": "eagle6-placer",
            "version": __version__,
            "source_board": str(board.source_path),
            "eagle_version": board.eagle_version,
            "script_path": str(script_path) if script_path else None,
            "seed": result.seed,
            "steps_executed": result.steps_executed,
            "accepted_moves": result.accepted_moves,
            "feasible_proposals": result.feasible_proposals,
            "rejected_infeasible": result.rejected_infeasible,
            "runtime_seconds": round(result.runtime_seconds, 4),
            "component_counts": {
                "total": len(board.components),
                "locked": len(board.locked_components),
                "unlocked": len(board.unlocked_components),
                "modified": len(deltas),
            },
            "metrics": {
                "before": asdict(result.initial_cost),
                "after": asdict(result.best_cost),
            },
            "constraint_audit": {
                "passed": len(result.final_violations) == 0,
                "violation_count": len(result.final_violations),
                "violations": [asdict(v) for v in result.final_violations],
            },
            "deltas": [asdict(d) for d in deltas],
        }

    def write_outputs(
        self,
        board: BoardModel,
        result: OptimizationResult,
        output_dir: str | Path | None = None,
    ) -> tuple[Path, Path]:
        """Write ``<board_stem>_placed.scr`` and ``<board_stem>_placed.json``."""
        out_dir = (
            Path(output_dir).resolve()
            if output_dir is not None
            else board.source_path.parent / "placer"
        )
        out_dir.mkdir(parents=True, exist_ok=True)

        stem = board.source_path.stem
        script_path = out_dir / f"{stem}_placed.scr"
        report_path = out_dir / f"{stem}_placed.json"

        script_text = self.render_script(board, result)
        script_path.write_text(script_text, encoding="utf-8")

        report = self.build_report(board, result, script_path=script_path)
        report_path.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")

        return script_path, report_path
